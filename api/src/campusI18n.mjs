// Deep copy of a config object where every {en: "..."} label also gets ja/zh/vi/ru (when known).
export function withExtraLanguages(value) {
  if (Array.isArray(value)) return value.map(withExtraLanguages);
  if (!value || typeof value !== "object") return value;
  const out = {};
  for (const [k, v] of Object.entries(value)) out[k] = withExtraLanguages(v);
  const row = typeof value.en === "string" ? LABELS[value.en] : null;
  const more = typeof value.en === "string" ? MORE[value.en] : null;
  const all = row ? [...row, ...(more || [])] : null;
  if (all) EXTRA_LANGS.forEach((lang, i) => { if (out[lang] === undefined && all[i]) out[lang] = all[i]; });
  return out;
}

export const _labels = LABELS;
