-- SMEAG Campus app: student web app (/campus/), staff queue (/campus-admin/) and the SMEAG bot.
-- Paste into the Supabase SQL Editor (project nbph...) and run once. Safe to run again.
--
-- Read/written only by api/src/campus.mjs and api/src/campusBot.mjs with the service key, so RLS does
-- not apply to them. RLS is on with no policies: the anon/public key cannot read or change any of it.
--
-- Money rule: a request that costs e-money is NOT charged when the student submits it. The app shows
-- "available = balance - fees of pending requests" and refuses a request the student cannot cover.
-- The fee is charged once, when staff approve it (campus_decide_request), as one bank row
-- (category 'SMEAG App', transaction_source 'CAMPUS APP', remark 'N', "order" = staff login_id).

-- ---------- student accounts (one per person row) ----------
create table if not exists public.campus_accounts (
  person_id          integer primary key,          -- person.id
  pin_hash           text,                         -- scrypt$<salt>$<hash>; null until the student sets a PIN
  activation_hash    text,                         -- office one-time code (sha256), for students without NFC phones
  activation_expires timestamptz,
  failed_count       integer not null default 0,
  locked_until       timestamptz,
  token_version      integer not null default 1,   -- bumped on PIN change/reset: old sessions stop working
  card_frozen        boolean not null default false,
  frozen_at          timestamptz,
  lang               text not null default 'en' check (lang in ('en', 'ko', 'ja', 'zh', 'vi', 'ru', 'cn', 'es')),
  created_at         timestamptz not null default now(),
  last_login_at      timestamptz
);
-- App languages (2026-11-16): English, Korean, Japanese, Traditional Chinese, Vietnamese, Russian.
alter table public.campus_accounts drop constraint if exists campus_accounts_lang_check;
alter table public.campus_accounts add constraint campus_accounts_lang_check check (lang in ('en', 'ko', 'ja', 'zh', 'vi', 'ru', 'cn', 'es'));

-- ---------- notices ----------
create table if not exists public.campus_notices (
  id           bigint generated by default as identity primary key,
  campus       text,                               -- null = every campus
  title_en     text not null,
  title_ko     text,
  body_en      text not null,
  body_ko      text,
  pinned       boolean not null default false,
  published_at timestamptz not null default now(),
  expires_at   timestamptz,
  created_by   text,
  created_at   timestamptz not null default now()
);
create index if not exists campus_notices_pub on public.campus_notices (published_at desc);

-- ---------- priced items: activities, pickup routes, rental cars, courses ----------
create table if not exists public.campus_catalog (
  id        bigint generated by default as identity primary key,
  kind      text not null check (kind in ('activity', 'pickup', 'car', 'course')),
  campus    text,                                  -- null = every campus
  title_en  text not null,
  title_ko  text,
  detail_en text,
  detail_ko text,
  fee       numeric(12,2) not null default 0 check (fee >= 0),
  fee_unit  text not null default 'once' check (fee_unit in ('once', 'day', 'week')),
  starts_at timestamptz,                           -- activities: when it happens
  capacity  integer check (capacity is null or capacity > 0),
  active    boolean not null default true,
  sort      integer not null default 0,
  created_at timestamptz not null default now()
);

-- ---------- requests (one engine for every type) ----------
create table if not exists public.campus_requests (
  id             bigint generated by default as identity primary key,
  person_id      integer not null,
  uid            citext,
  studentid      citext,
  name           text,
  campus         text,
  type           text not null check (type in ('activity', 'room_change', 'cleaning', 'clinic', 'overnight',
                   'graduation', 'checkout', 'pickup', 'car_rental', 'course_change', 'refund')),
  catalog_id     bigint,
  payload        jsonb not null default '{}'::jsonb,
  fee            numeric(12,2) not null default 0 check (fee >= 0),
  status         text not null default 'submitted'
                   check (status in ('submitted', 'reviewing', 'approved', 'rejected', 'cancelled', 'done')),
  staff_note     text,
  handled_by     text,
  handled_at     timestamptz,
  charge_bank_id bigint,                           -- bank.id of the fee row, once charged
  client_key     text not null,                    -- one per form submit: a double tap creates one request
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  unique (person_id, client_key)
);
create index if not exists campus_requests_queue on public.campus_requests (status, created_at);
create index if not exists campus_requests_person on public.campus_requests (person_id, created_at desc);

-- ---------- TOEFL / IELTS mock test scores (imported by the office) ----------
create table if not exists public.campus_scores (
  id         bigint generated by default as identity primary key,
  person_id  integer,
  studentid  citext not null,
  test       text not null check (test in ('IELTS', 'TOEFL')),
  test_date  date not null,
  listening  numeric(5,1),
  reading    numeric(5,1),
  writing    numeric(5,1),
  speaking   numeric(5,1),
  overall    numeric(5,1),
  comment    text,
  created_by text,
  created_at timestamptz not null default now(),
  unique (studentid, test, test_date)
);

-- ---------- SMEAG bot ----------
create table if not exists public.campus_bot_faq (
  id       bigint generated by default as identity primary key,
  campus   text,                                   -- null = every campus
  question text not null,
  answer   text not null,
  keywords text,                                   -- extra words for matching, any language
  active   boolean not null default true,
  sort     integer not null default 0
);

create table if not exists public.campus_bot_log (
  id         bigint generated by default as identity primary key,
  person_id  integer,
  question   text not null,
  answer     text,
  source     text,                                 -- 'claude' | 'faq'
  created_at timestamptz not null default now()
);

-- ---------- lock everything down ----------
do $$
declare t text;
begin
  foreach t in array array['campus_accounts', 'campus_notices', 'campus_catalog', 'campus_requests',
                           'campus_scores', 'campus_bot_faq', 'campus_bot_log'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
    execute format('grant select, insert, update, delete on public.%I to service_role', t);
  end loop;
  grant usage, select on all sequences in schema public to service_role;
end $$;

-- ---------- submit: checks the student can cover the fee, idempotent per client_key ----------
create or replace function public.campus_submit_request(
    p_person_id  integer,
    p_type       text,
    p_catalog_id bigint,
    p_payload    jsonb,
    p_fee        numeric,
    p_client_key text
)
returns jsonb
language plpgsql
set search_path = public, extensions
as $$
declare
    v_person    public.person%rowtype;
    v_pending   numeric(14,2);
    v_existing  public.campus_requests%rowtype;
    v_row       public.campus_requests%rowtype;
begin
    if coalesce(p_client_key, '') = '' then
        raise sqlstate 'PT400' using message = 'client_key is required.';
    end if;
    if p_fee is null or p_fee < 0 then
        raise sqlstate 'PT400' using message = 'Fee must be 0 or more.';
    end if;

    -- Lock the student so two submissions cannot both spend the same balance.
    select * into v_person from public.person where id = p_person_id for update;
    if not found then
        raise sqlstate 'PT404' using message = 'Student not found.';
    end if;

    select * into v_existing from public.campus_requests
     where person_id = p_person_id and client_key = p_client_key;
    if found then
        return to_jsonb(v_existing);
    end if;

    if p_fee > 0 then
        select coalesce(sum(fee), 0) into v_pending from public.campus_requests
         where person_id = p_person_id and status in ('submitted', 'reviewing') and charge_bank_id is null;
        if coalesce(v_person.totalmoney, 0) - v_pending < p_fee then
            raise sqlstate 'PT409' using message = format(
              'Not enough e-money. Available: %s, needed: %s.',
              to_char(coalesce(v_person.totalmoney, 0) - v_pending, 'FM999,999,990.00'),
              to_char(p_fee, 'FM999,999,990.00'));
        end if;
    end if;

    insert into public.campus_requests (person_id, uid, studentid, name, campus, type, catalog_id, payload, fee, client_key)
    values (p_person_id, v_person.uid, v_person.studentid, v_person.name, v_person.campus, p_type, p_catalog_id,
            coalesce(p_payload, '{}'::jsonb), round(p_fee, 2), p_client_key)
    returning * into v_row;
    return to_jsonb(v_row);
end $$;

-- ---------- staff decision: the only place a fee is charged ----------
create or replace function public.campus_decide_request(
    p_id     bigint,
    p_status text,
    p_staff  text,
    p_note   text
)
returns jsonb
language plpgsql
set search_path = public, extensions
as $$
declare
    v_req     public.campus_requests%rowtype;
    v_person  public.person%rowtype;
    v_before  numeric(14,2);
    v_after   numeric(14,2);
    v_bank_id bigint;
    v_label   text;
begin
    if coalesce(p_staff, '') = '' then
        raise sqlstate 'PT401' using message = 'Staff login is required.';
    end if;

    select * into v_req from public.campus_requests where id = p_id for update;
    if not found then
        raise sqlstate 'PT404' using message = 'Request not found.';
    end if;

    if not (
        (v_req.status = 'submitted' and p_status in ('reviewing', 'approved', 'rejected')) or
        (v_req.status = 'reviewing' and p_status in ('approved', 'rejected')) or
        (v_req.status = 'approved'  and p_status = 'done')
    ) then
        raise sqlstate 'PT409' using message = format('A %s request cannot be changed to %s.', v_req.status, p_status);
    end if;
    if p_status = 'rejected' and coalesce(btrim(p_note), '') = '' then
        raise sqlstate 'PT400' using message = 'Write the reason for the student when rejecting.';
    end if;

    if p_status = 'approved' and v_req.fee > 0 and v_req.charge_bank_id is null then
        select * into v_person from public.person where id = v_req.person_id for update;
        if not found then
            raise sqlstate 'PT404' using message = 'The student of this request no longer exists.';
        end if;
        v_before := coalesce(v_person.totalmoney, 0);
        if v_before < v_req.fee then
            raise sqlstate 'PT409' using message = format(
              'The student has only %s e-money; this request needs %s. Ask them to top up first.',
              to_char(v_before, 'FM999,999,990.00'), to_char(v_req.fee, 'FM999,999,990.00'));
        end if;
        v_after := v_before - v_req.fee;
        v_label := left(initcap(replace(v_req.type, '_', ' ')) || coalesce(' #' || v_req.id, ''), 120);

        insert into public.bank (uid, studentid, name, campus, beforeamount, category, subcategory,
                                 transaction_type, payment, totalmoney, quantity,
                                 transaction_source, remark, "order")
        values (v_person.uid, coalesce(v_person.studentid, ''), coalesce(v_person.name, ''), v_person.campus,
                v_before, 'SMEAG App', v_label, 'decrease', v_req.fee, v_after, 1,
                'CAMPUS APP', 'N', p_staff)
        returning id into v_bank_id;

        update public.person set totalmoney = v_after where id = v_person.id;
        v_req.charge_bank_id := v_bank_id;
    end if;

    update public.campus_requests
       set status = p_status,
           staff_note = coalesce(nullif(btrim(p_note), ''), staff_note),
           handled_by = p_staff,
           handled_at = now(),
           charge_bank_id = v_req.charge_bank_id,
           updated_at = now()
     where id = p_id
    returning * into v_req;
    return to_jsonb(v_req);
end $$;

-- ---------- student cancels their own pending request ----------
create or replace function public.campus_cancel_request(p_id bigint, p_person_id integer)
returns jsonb
language plpgsql
set search_path = public, extensions
as $$
declare v_req public.campus_requests%rowtype;
begin
    select * into v_req from public.campus_requests where id = p_id and person_id = p_person_id for update;
    if not found then
        raise sqlstate 'PT404' using message = 'Request not found.';
    end if;
    if v_req.status not in ('submitted', 'reviewing') then
        raise sqlstate 'PT409' using message = 'Only a request that is still waiting can be cancelled.';
    end if;
    update public.campus_requests set status = 'cancelled', updated_at = now() where id = p_id returning * into v_req;
    return to_jsonb(v_req);
end $$;

revoke execute on function public.campus_submit_request(integer, text, bigint, jsonb, numeric, text) from public, anon, authenticated;
revoke execute on function public.campus_decide_request(bigint, text, text, text) from public, anon, authenticated;
revoke execute on function public.campus_cancel_request(bigint, integer) from public, anon, authenticated;
grant  execute on function public.campus_submit_request(integer, text, bigint, jsonb, numeric, text) to service_role;
grant  execute on function public.campus_decide_request(bigint, text, text, text) to service_role;
grant  execute on function public.campus_cancel_request(bigint, integer) to service_role;

