-- Student outing (외출) / overnight stay (외박) log for the office OUTING tab (api/src/outing.mjs).
-- Paste into the Supabase SQL Editor (project nbph...) and run once. Safe to run again.
--
-- One row = one time a student left the campus. The student taps the e-money card at the office:
--   1st tap  -> staff choose OUTING or OVERNIGHT + expected return time -> row created (out_at)
--   next tap -> returned_at is filled (back on campus)
-- Rows with returned_at null are "still out"; past expected_return_at they are LATE.
-- A wrong entry is voided (voided_at), never deleted. client_key stops a double submit.

create table if not exists public.student_outing (
    id                  bigint generated by default as identity primary key,
    person_id           integer references public.person(id) on delete set null,
    uid                 text,
    student_id          text,
    student_name        text not null,
    campus              text not null,
    kind                text not null check (kind in ('OUTING', 'OVERNIGHT')),
    destination         text,
    memo                text,
    out_at              timestamptz not null default now(),
    expected_return_at  timestamptz not null,
    out_by              text,
    returned_at         timestamptz,
    returned_by         text,
    client_key          text unique,
    voided_at           timestamptz,
    voided_by           text,
    void_reason         text,
    check (expected_return_at > out_at),
    check (returned_at is null or returned_at >= out_at)
);
create index if not exists student_outing_out_at on public.student_outing (out_at desc);
create index if not exists student_outing_person on public.student_outing (person_id);
-- a student can be out only once at a time
create unique index if not exists student_outing_one_open
    on public.student_outing (person_id) where returned_at is null and voided_at is null;
alter table public.student_outing enable row level security;   -- service_role only

