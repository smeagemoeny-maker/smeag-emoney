-- Office REGISTRATION > IMPORT FROM EXCEL (setup schedule, NEW students only): import history.
-- Paste into the Supabase SQL Editor (project nbph...) and run once. Safe to run again.
--
-- One row per student created by the import. person_id points at the person row it created
-- (no foreign key: Graduate moves people to person_graduate_backup and deletes them from person,
-- and the history should survive that).

create table if not exists public.person_import (
    id           bigint generated by default as identity primary key,
    person_id    bigint,
    studentid    text,
    name         text not null,
    name_key     text not null,              -- upper-case name without "(family)" etc., used for the duplicate check
    campus       text,
    nat          text,
    room         text,
    course       text,
    age          integer,
    gender       text,
    s_date       date,
    e_date       date,
    file_name    text,
    imported_by  text,
    imported_at  timestamptz not null default now()
);

create index if not exists person_import_imported_at_idx on public.person_import (imported_at);
create index if not exists person_import_name_key_idx on public.person_import (name_key, s_date);
create index if not exists person_import_person_id_idx on public.person_import (person_id);

-- Only the server (service key) reads/writes this table.
alter table public.person_import enable row level security;
