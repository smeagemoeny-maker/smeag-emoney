-- Local Fee (visa / SSP / I-Card / deposit / utilities / pick-up) sheets and the payments received for them.
-- Used by the /simulator page (api/src/localFee.mjs). Paste into the Supabase SQL Editor (project nbph...) and run once.
-- Safe to run again.
--
-- local_fee_record  : one fee sheet per student stay. items = the calculated lines
--                     [{key, name, amount, detail}], e.g. key visa_ext_1, ssp, ssp_icard, visa_icard, deposit, util, elec, pickup.
--                     The sheet can be recalculated later (extension); payments stay attached by item key.
-- local_fee_payment : money received for one item of a sheet (cash/GCash/...). It does NOT touch the e-money card.
--                     A wrong entry is voided (voided_at), never deleted. client_key stops a double submit.

create table if not exists public.local_fee_record (
    id            bigint generated by default as identity primary key,
    person_id     integer references public.person(id) on delete set null,
    uid           text,
    student_id    text,
    student_name  text not null,
    campus        text not null,
    entry_type    text not null,          -- G30 | G59 | C30 | C14 | C7 (see /simulator)
    preset        text not null,          -- fee table version, e.g. 2025-07 | 2027
    weeks         integer not null check (weeks between 1 and 104),
    extra_days    integer not null default 0 check (extra_days between 0 and 120),
    arrival_date  date,
    pickup        boolean not null default false,
    ssp_again     boolean not null default false,
    items         jsonb not null,
    total         numeric(12,2) not null,
    memo          text,
    status        text not null default 'active' check (status in ('active', 'cancelled')),
    created_by    text,
    created_at    timestamptz not null default now(),
    updated_by    text,
    updated_at    timestamptz not null default now()
);
create index if not exists local_fee_record_person on public.local_fee_record (person_id);
create index if not exists local_fee_record_created on public.local_fee_record (created_at desc);
alter table public.local_fee_record enable row level security;   -- service_role only

create table if not exists public.local_fee_payment (
    id            bigint generated by default as identity primary key,
    record_id     bigint not null references public.local_fee_record(id) on delete restrict,
    item_key      text not null,
    item_name     text,
    amount        numeric(12,2) not null check (amount > 0),
    method        text not null check (method in ('CASH', 'GCASH', 'BANK', 'CARD', 'OTHER')),
    memo          text,
    client_key    text unique,
    received_by   text,
    received_at   timestamptz not null default now(),
    voided_at     timestamptz,
    voided_by     text,
    void_reason   text
);
create index if not exists local_fee_payment_record on public.local_fee_payment (record_id);
create index if not exists local_fee_payment_received on public.local_fee_payment (received_at desc);
alter table public.local_fee_payment enable row level security;  -- service_role only

