-- smeadmin.com refunds (Alipay "student allowance" etc.) -> e-money office refund, linked by passport.
-- Paste into the Supabase SQL Editor (project nbph...) and run once. Safe to run again.
--
-- student_identity : one row per passport. The full passport number is NOT stored:
--                    passport_hash = HMAC-SHA256(PASSPORT_HMAC_SECRET, normalized number) computed by the API,
--                    passport_last4 is only for display. person_id is the e-money card owner (person.id).
-- smeadmin_refund  : one row per smeadmin change request (change_no = modify_no in student_list_change.php).
--                    paid_txn_id points at the office transaction; the payout itself goes through
--                    pos_office_transaction with client_key 'sme-<change_no>', so it can never be paid twice.

create table if not exists public.student_identity (
    id              bigint generated by default as identity primary key,
    passport_hash   text not null unique,
    passport_last4  text not null,
    name_en         text,
    birth_date      date,
    person_id       integer references public.person(id) on delete set null,
    linked_by       text,          -- staff login_id that linked the card (null = not linked yet)
    linked_at       timestamptz,
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now()
);
create index if not exists student_identity_person on public.student_identity (person_id);
alter table public.student_identity enable row level security;   -- service_role only

create table if not exists public.smeadmin_refund (
    change_no       integer primary key,          -- smeadmin modify_no of the change request (e.g. 27812)
    sme_student_no  integer,                      -- smeadmin student registration no (e.g. 103123), when known
    name_en         text not null,
    agency          text,
    campus          text,
    applied_at      text,                         -- as shown by smeadmin, e.g. 2026-11-19(14:53:12)
    amount_text     text,                         -- raw "Target refund amount", e.g. 10,000P
    amount_php      numeric(12,2),
    note            text,                         -- raw "Refund Info Details"
    rmb             numeric(12,2),
    rate            numeric(10,4),
    check_diff      numeric(12,2),                -- rmb*rate - amount_php (null when the note has no RMB/rate)
    kind            text,                         -- allowance (paid from the e-money card) | other (info only)
    currency        text,                         -- PHP | USD | RMB | KRW | JPY, from the amount box
    sme_process     text,                         -- normal | cancel | waiting
    sme_result      text,                         -- center | account | collection | refund | holding | cancel
    passport_hash   text,
    passport_last4  text,
    status          text not null default 'pending'
                    -- pending: ready to pay | mismatch: amount vs RMB note | paid: paid here
                    -- cancelled: cancelled in smeadmin | paid_then_cancelled: paid here, cancelled later (check!)
                    -- closed: smeadmin marked it done (e.g. 환급완료) without this screen
                    -- other: not a student allowance (course shortening, tuition...): shown, never paid here
                    check (status in ('pending', 'mismatch', 'paid', 'cancelled', 'paid_then_cancelled', 'closed', 'other')),
    paid_txn_id     bigint,
    paid_uid        text,
    paid_by         text,
    paid_at         timestamptz,
    first_seen_at   timestamptz not null default now(),
    synced_at       timestamptz not null default now()
);
create index if not exists smeadmin_refund_status on public.smeadmin_refund (status);
create index if not exists smeadmin_refund_passport on public.smeadmin_refund (passport_hash);
alter table public.smeadmin_refund enable row level security;    -- service_role only

-- Last sync run (one row), so the office screen can show "synced 3 min ago" and errors.
create table if not exists public.smeadmin_sync_state (
    id          integer primary key default 1 check (id = 1),
    last_run_at timestamptz,
    last_ok_at  timestamptz,
    last_error  text,
    last_count  integer
);
insert into public.smeadmin_sync_state (id) values (1) on conflict (id) do nothing;
alter table public.smeadmin_sync_state enable row level security;

